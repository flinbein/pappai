import { spawn } from 'node:child_process';
import { readFileSync } from 'node:fs';
import type { IncomingMessage, Server } from 'node:http';
import type { Readable } from 'node:stream';
import { WebSocket, WebSocketServer } from 'ws';
import type { Store } from './store.ts';
import { sandboxArgs } from './sandbox.ts';
import { isWebRpcSocket } from './events.ts';

const bridge = readFileSync(new URL('./terminal-pty.py', import.meta.url), 'utf8');
const limit = 1024 * 1024;
type SessionUser = (req: IncomingMessage, touch?: boolean) => string | null;

function launch(store: Store, user: string, forceSandbox: boolean) {
  if (process.platform !== 'linux') throw Error('Для веб-терминала требуется Linux-контейнер pappai');
  const sandbox = store.sandbox(user) ?? (forceSandbox ? {read: [], write: [], network: false} : null);
  const cwd = sandbox ? '/tmp' : '/root';
  const env = {TERM: 'xterm-256color', HOME: cwd, LANG: 'C.UTF-8', PATH: '/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin'};
  const settings = {cwd, command: '/usr/bin/python3', env};
  const args = ['-I', '-c', bridge];
  if (!sandbox) return {sandboxed: false, child: spawn(settings.command, args, {cwd, env, stdio: 'pipe'})};
  const options = sandboxArgs({appId: user, sandbox, settings});
  // All arguments are generated by the controller and contain no secrets.
  const child = spawn('/usr/bin/bwrap', [...options, '--', settings.command, ...args], {
    env: {PATH: env.PATH}, stdio: ['pipe', 'pipe', 'pipe', 'ignore', 'pipe'],
  });
  (child.stdio[4] as Readable).resume();
  return {sandboxed: true, child};
}

export function attachTerminals(server: Server, address: URL, store: Store, user: SessionUser) {
  const wss = new WebSocketServer({noServer: true, maxPayload: 65536, perMessageDeflate: false});
  const terminals = new Map<WebSocket, {valid(): boolean; done: Promise<void>}>();
  let closing = false;

  server.on('upgrade', (req, socket, head) => {
    if (isWebRpcSocket(req.url)) return;
    function reject(status: string) {
      socket.end('HTTP/1.1 ' + status + '\r\nConnection: close\r\nContent-Length: 0\r\n\r\n');
    }
    const forceSandbox = req.url === '/api/ws/terminal?sandbox=1' || req.url === '/ws/terminal?sandbox=1';
    if (closing || (!forceSandbox && req.url !== '/api/ws/terminal' && req.url !== '/ws/terminal'))
      return reject('404 Not Found');
    if (req.headers.origin !== address.origin || req.headers.host !== address.host) return reject('403 Forbidden');
    const actor = user(req);
    if (!actor) return reject('401 Unauthorized');
    wss.handleUpgrade(req, socket, head, ws => {
      ws.on('error', () => ws.terminate());
      let processInfo;
      try { processInfo = launch(store, actor, forceSandbox); }
      catch (error) {
        ws.send(JSON.stringify({error: (error as Error).message}));
        ws.close(1011);
        return;
      }
      const {child, sandboxed} = processInfo;
      const input = child.stdin!;
      let stopped = false, alive = true;
      let unrendered = 0;
      let diagnostic = '';
      const done = new Promise<void>(resolve => child.once('close', () => resolve()));
      const valid = () => user(req, false) === actor;
      terminals.set(ws, {valid, done});
      function stop() {
        if (stopped) return;
        stopped = true;
        input.end();
        if (child.exitCode === null && child.signalCode === null) {
          // bwrap --die-with-parent tears down namespace PID 1 on supervisor death.
          // The direct bridge instead closes its PTY and kills its own shell.
          child.kill(sandboxed ? 'SIGKILL' : 'SIGTERM');
        }
      }
      ws.once('close', stop);
      ws.on('pong', () => { alive = true; });
      const heartbeat = setInterval(() => {
        if (!alive || !valid()) return ws.terminate();
        alive = false;
        ws.ping();
      }, 15000);
      heartbeat.unref();
      ws.send(JSON.stringify({sandboxed}));
      child.stderr!.on('data', chunk => { diagnostic = (diagnostic + chunk.toString()).slice(-2048); });
      child.on('error', error => { diagnostic = error.message; });
      input.on('error', () => {});
      const output = child.stdout!;
      output.on('data', (chunk: Buffer) => {
        if (ws.readyState !== WebSocket.OPEN) return;
        if (ws.bufferedAmount > limit) return ws.terminate();
        unrendered += chunk.length;
        if (unrendered >= 131072) output.pause();
        ws.send(chunk);
      });
      ws.on('message', (raw, binary) => {
        if (stopped || !user(req, binary) || input.writableLength > limit) return ws.terminate();
        const bytes = Buffer.isBuffer(raw) ? raw : Buffer.from(raw as ArrayBuffer);
        let data = bytes;
        if (!binary) {
          try {
            const {cols, rows, rendered} = JSON.parse(bytes.toString());
            if (rendered !== undefined) {
              if (!Number.isInteger(rendered) || rendered < 1 || rendered > unrendered) throw Error();
              unrendered -= rendered;
              if (unrendered < 65536) output.resume();
              return;
            }
            if (![cols, rows].every(n => Number.isInteger(n) && n >= 1 && n <= 1000)) throw Error();
            data = Buffer.alloc(4);
            data.writeUInt16BE(rows, 0);
            data.writeUInt16BE(cols, 2);
          } catch { ws.close(1008, 'Invalid terminal control'); stop(); return; }
        }
        const header = Buffer.alloc(5);
        header[0] = binary ? 1 : 2;
        header.writeUInt32BE(data.length, 1);
        input.write(Buffer.concat([header, data]));
      });
      child.once('close', code => {
        clearInterval(heartbeat);
        terminals.delete(ws);
        if (ws.readyState === WebSocket.OPEN) {
          if (code !== 0) ws.send(JSON.stringify({error: diagnostic.trim() || 'Ошибка терминала'}));
          ws.close(code === 0 ? 1000 : 1011);
        }
      });
    });
  });
  return {
    checkSessions() {
      for (const [ws, terminal] of terminals) if (!terminal.valid()) ws.terminate();
    },
    async close() {
      closing = true;
      const pending = Array.from(terminals.values(), terminal => terminal.done);
      for (const ws of wss.clients) ws.terminate();
      wss.close();
      await Promise.all(pending);
    },
  };
}
